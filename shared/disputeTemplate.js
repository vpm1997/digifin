export function formatINR(amount) {
  return `₹${Number(amount || 0).toLocaleString('en-IN')}`;
}

export function buildDisputeLetter({ finding, account, holderName, bank }) {
  const today = new Date().toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
  const reference = `DFS-${String(finding.id || 'X').toUpperCase()}-${Date.now()
    .toString()
    .slice(-6)}`;

  return `To,
The Customer Care / Escalations Team
${bank}

Date: ${today}
Reference: ${reference}
Account: ${account}

Subject: Formal dispute — ${finding.title}

Dear Sir/Madam,

I am writing to dispute a charge of ${formatINR(finding.amount)} reflected on my account statement.

Description: ${finding.description || finding.title}
${finding.date ? `Transaction date: ${finding.date}\n` : ''}Category: ${finding.category}
${finding.citation ? `Reference: ${finding.citation}\n` : ''}

${finding.reason || 'This charge does not appear to be authorised or correctly computed under the applicable schedule of charges.'}

I request that you:
1. Review this transaction against the signed Most Important Terms & Conditions (MITC) and the applicable regulatory guidelines.
2. Reverse the disputed amount of ${formatINR(finding.amount)} along with any consequential interest or charges.
3. Confirm the resolution in writing within 7 business days.

If I do not receive a satisfactory response within this period, I will escalate the matter to the Banking Ombudsman under the Reserve Bank of India's Integrated Ombudsman Scheme, 2021.

All correspondence may be sent to the contact details on record for this account.

Yours sincerely,
${holderName || '[Your name]'}

---
Generated by DigiFinSaviour. Please review before sending.`;
}
